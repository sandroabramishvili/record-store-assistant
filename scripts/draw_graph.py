"""Write the graph's Mermaid diagram to docs/graph.md (guide 10.7). No Gemini, no database.

    python -m scripts.draw_graph

The diagram is generated from the compiled graph itself, so it always matches the code.
GitHub renders ```mermaid blocks, so docs/graph.md (and the README) show it as a picture.
"""

from pathlib import Path

from app.ai.deps import Deps
from app.ai.graph import build_graph

OUT = Path(__file__).resolve().parents[1] / 'docs' / 'graph.md'


class _NoLLM:
    """Drawing needs the structure only; no model is ever called."""

    def with_structured_output(self, schema):
        return self

    def with_retry(self, **kwargs):
        return self


def mermaid() -> str:
    graph = build_graph(Deps(llm=_NoLLM(), repo=None))
    return graph.get_graph().draw_mermaid()


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        '# Store assistant graph\n\n'
        'Generated by `python -m scripts.draw_graph` from the compiled LangGraph graph. '
        'Dotted arrows are conditional (decided by `app/ai/routing.py`).\n\n'
        f'```mermaid\n{mermaid()}```\n',
        encoding='utf-8',
    )
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
